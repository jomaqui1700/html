CREATE OR REPLACE FUNCTION apply_coffee_inventory_movement() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE delta numeric;
BEGIN
  delta := CASE WHEN NEW.movement_type IN ('entrada','ajuste_positivo') THEN NEW.quantity ELSE -NEW.quantity END;
  UPDATE coffee_inventory SET current_stock = current_stock + delta WHERE id = NEW.inventory_id AND current_stock + delta >= 0;
  IF NOT FOUND THEN RAISE EXCEPTION 'Inventario de café insuficiente o producto inexistente'; END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_coffee_inventory_movement ON coffee_inventory_movements;
CREATE TRIGGER trg_coffee_inventory_movement BEFORE INSERT ON coffee_inventory_movements FOR EACH ROW EXECUTE FUNCTION apply_coffee_inventory_movement();

CREATE OR REPLACE FUNCTION apply_cattle_inventory_movement() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE delta numeric;
BEGIN
  delta := CASE WHEN NEW.movement_type IN ('entrada','ajuste_positivo') THEN NEW.quantity ELSE -NEW.quantity END;
  UPDATE cattle_inventory SET current_stock = current_stock + delta WHERE id = NEW.inventory_id AND current_stock + delta >= 0;
  IF NOT FOUND THEN RAISE EXCEPTION 'Inventario de ganado insuficiente o producto inexistente'; END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_cattle_inventory_movement ON cattle_inventory_movements;
CREATE TRIGGER trg_cattle_inventory_movement BEFORE INSERT ON cattle_inventory_movements FOR EACH ROW EXECUTE FUNCTION apply_cattle_inventory_movement();

CREATE OR REPLACE FUNCTION deduct_coffee_application_inventory() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.inventory_item_id IS NOT NULL AND NEW.quantity_used IS NOT NULL THEN
    INSERT INTO coffee_inventory_movements(inventory_id,movement_date,movement_type,quantity,reference_type,reference_id,notes,created_by)
    VALUES(NEW.inventory_item_id,NEW.application_date,'salida',NEW.quantity_used,'farm_application',NEW.id,'Consumo automático por aplicación',NEW.created_by);
  END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_deduct_coffee_application ON farm_applications;
CREATE TRIGGER trg_deduct_coffee_application AFTER INSERT ON farm_applications FOR EACH ROW EXECUTE FUNCTION deduct_coffee_application_inventory();

CREATE OR REPLACE FUNCTION deduct_cattle_treatment_inventory() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.inventory_item_id IS NOT NULL AND NEW.dose IS NOT NULL THEN
    INSERT INTO cattle_inventory_movements(inventory_id,movement_date,movement_type,quantity,reference_type,reference_id,notes,created_by)
    VALUES(NEW.inventory_item_id,NEW.application_date,'salida',NEW.dose,'cattle_treatment',NEW.id,'Consumo automático por tratamiento',NEW.created_by);
  END IF;
  RETURN NEW;
END; $$;

DROP TRIGGER IF EXISTS trg_deduct_cattle_treatment ON cattle_treatments;
CREATE TRIGGER trg_deduct_cattle_treatment AFTER INSERT ON cattle_treatments FOR EACH ROW EXECUTE FUNCTION deduct_cattle_treatment_inventory();
